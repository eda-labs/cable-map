import react from '@vitejs/plugin-react'
import fs from 'node:fs'
import path from 'node:path'
import { randomUUID } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import type { IncomingMessage, ServerResponse } from 'node:http'
import { DevPdfRequestError, renderDevPdf, type DevPdfProgress, type DevPdfTopology } from './dev/pdf'

// The dev server uses a small local topology mock by default. Set EDA_API=http://... to proxy
// /api + /pdf to a real cable-map backend instead. Without EDA_API, /api is mocked from the
// golden topology fixture and /pdf renders that same mock via Typst. Front-panel metadata is a
// static file (src/generated/frontpanel-meta.json, regenerated by the frontpanel-studio tooling
// project); the SVG panels are served by the operator (here in dev, by the `frontpanel` plugin below)
// as plain assets.
const edaApi = process.env.EDA_API
const apiTarget = edaApi && /^https?:\/\//.test(edaApi) ? edaApi : ''
// MOCK_TOPOLOGY=/abs/path.json overrides the bundled golden topology, for previewing ad-hoc fixtures.
const mockTopologyEntries = process.env.MOCK_TOPOLOGY ? [
  { namespace: 'demo', path: new URL(`file://${process.env.MOCK_TOPOLOGY}`) },
] : [
  { namespace: 'demo', path: new URL('../operators/cable-map/internal/topology/testdata/golden-topology.json', import.meta.url) },
  { namespace: 'dev-mixed-sros', path: new URL('./dev/fixtures/mixed-sros-topology.json', import.meta.url) },
  { namespace: 'dev-scale-1000', path: new URL('./dev/fixtures/large-1000-topology.json', import.meta.url) },
  { namespace: 'dev-ai-fabric-196', path: new URL('./dev/fixtures/ai-fabric-196-topology.json', import.meta.url) },
]
const mockNamespaces = mockTopologyEntries.map((entry) => entry.namespace)
const defaultMockNamespace = mockNamespaces[0] ?? 'demo'

const sendJSON = (res: ServerResponse, status: number, body: unknown) => {
  res.statusCode = status
  res.setHeader('Content-Type', 'application/json')
  res.end(JSON.stringify(body))
}

const sendPDF = (res: ServerResponse, body: Buffer, filename: string) => {
  res.statusCode = 200
  res.setHeader('Content-Type', 'application/pdf')
  res.setHeader('Content-Disposition', `inline; filename="${filename}"`)
  res.end(body)
}

type MockPdfProgressEvent = {
  status: 'running' | 'ready' | 'error'
  phase: string
  detail?: string
  percent?: number
  indeterminate?: boolean
  message?: string
}

type MockPdfJobRequest = {
  namespace?: unknown
  nodes?: unknown
  remote?: unknown
  stencils?: unknown
}

type MockPdfJob = {
  id: string
  event: MockPdfProgressEvent
  subscribers: Set<ServerResponse>
  bytes?: Buffer
  filename?: string
  expiresAt?: number
}

const pdfJobTtlMs = 10 * 60 * 1000

const readJSONBody = (req: IncomingMessage): Promise<MockPdfJobRequest> => new Promise((resolve, reject) => {
  let body = ''
  req.setEncoding('utf8')
  req.on('data', (chunk: string) => {
    body += chunk
    if (body.length > 4 * 1024 * 1024) reject(new Error('request body too large'))
  })
  req.on('end', () => {
    if (!body.trim()) { resolve({}); return }
    try { resolve(JSON.parse(body) as MockPdfJobRequest) } catch (error) { reject(error) }
  })
  req.on('error', reject)
})

const stringArray = (value: unknown): string[] =>
  Array.isArray(value) ? value.map((item) => String(item).trim()).filter(Boolean) : []

const stringRecord = (value: unknown): Record<string, string> => {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return {}
  const out: Record<string, string> = {}
  for (const [key, recordValue] of Object.entries(value)) {
    if (recordValue != null) out[key] = String(recordValue)
  }
  return out
}

const sendSSE = (req: IncomingMessage, res: ServerResponse, payload: string) => {
  res.statusCode = 200
  res.setHeader('Content-Type', 'text/event-stream')
  res.setHeader('Cache-Control', 'no-cache')
  res.setHeader('Connection', 'keep-alive')
  res.write('retry: 3000\n\n')
  res.write(`data: ${payload}\n\n`)
  const timer = setInterval(() => res.write(': ping\n\n'), 25000)
  req.on('close', () => clearInterval(timer))
}

const sendHeartbeatSSE = (req: IncomingMessage, res: ServerResponse) => {
  res.statusCode = 200
  res.setHeader('Content-Type', 'text/event-stream')
  res.setHeader('Cache-Control', 'no-cache')
  res.setHeader('Connection', 'keep-alive')
  res.write('retry: 3000\n\n')
  const timer = setInterval(() => res.write(': ping\n\n'), 25000)
  req.on('close', () => clearInterval(timer))
}

const writePdfJobEvent = (res: ServerResponse, event: MockPdfProgressEvent) => {
  res.write(`data: ${JSON.stringify(event)}\n\n`)
}

const updatePdfJob = (job: MockPdfJob, event: MockPdfProgressEvent) => {
  job.event = event
  if (event.status !== 'running') job.expiresAt = Date.now() + pdfJobTtlMs
  for (const res of job.subscribers) {
    writePdfJobEvent(res, event)
    if (event.status !== 'running') res.end()
  }
  if (event.status !== 'running') job.subscribers.clear()
}

const sendPdfJobSSE = (req: IncomingMessage, res: ServerResponse, job: MockPdfJob) => {
  res.statusCode = 200
  res.setHeader('Content-Type', 'text/event-stream')
  res.setHeader('Cache-Control', 'no-cache')
  res.setHeader('Connection', 'keep-alive')
  res.write('retry: 3000\n\n')
  writePdfJobEvent(res, job.event)
  if (job.event.status !== 'running') {
    res.end()
    return
  }
  job.subscribers.add(res)
  const timer = setInterval(() => res.write(': ping\n\n'), 25000)
  req.on('close', () => {
    clearInterval(timer)
    job.subscribers.delete(res)
  })
}

const mockApiPlugin = (): Plugin => ({
  name: 'cable-map-dev-api',
  configureServer(server: ViteDevServer) {
    const topologies = new Map(mockTopologyEntries.map((entry) => {
      const data = JSON.parse(fs.readFileSync(entry.path, 'utf8')) as DevPdfTopology
      return [entry.namespace, { data, json: JSON.stringify(data) }]
    }))
    const pdfJobs = new Map<string, MockPdfJob>()
    const cleanupPdfJobs = () => {
      const now = Date.now()
      for (const [id, job] of pdfJobs) {
        if (job.expiresAt && now > job.expiresAt) pdfJobs.delete(id)
      }
    }
    const selectedTopology = (url: URL) => {
      const namespace = url.searchParams.get('ns')?.trim() || defaultMockNamespace
      return { namespace, topology: topologies.get(namespace) }
    }
    const selectedTopologyByNamespace = (namespace: string) => {
      const selected = namespace.trim() || defaultMockNamespace
      return { namespace: selected, topology: topologies.get(selected) }
    }
    const pdfUrlForJob = (body: MockPdfJobRequest, namespace: string) => {
      const pdfUrl = new URL('/pdf', 'http://localhost')
      pdfUrl.searchParams.set('ns', namespace)
      const nodes = stringArray(body.nodes)
      const remote = stringRecord(body.remote)
      const stencils = stringRecord(body.stencils)
      if (nodes.length) pdfUrl.searchParams.set('nodes', nodes.join(','))
      if (Object.keys(remote).length) pdfUrl.searchParams.set('remote', JSON.stringify(remote))
      if (Object.keys(stencils).length) pdfUrl.searchParams.set('stencils', JSON.stringify(stencils))
      return pdfUrl
    }

    server.middlewares.use((req: IncomingMessage, res: ServerResponse, next: (err?: unknown) => void) => {
      if (req.method !== 'GET') {
        const url = new URL(req.url ?? '/', 'http://localhost')
        if (req.method === 'POST' && url.pathname === '/api/pdf/jobs') {
          void readJSONBody(req)
            .then((body) => {
              cleanupPdfJobs()
              const namespace = typeof body.namespace === 'string' ? body.namespace : ''
              const selected = selectedTopologyByNamespace(namespace)
              if (!selected.topology) {
                sendJSON(res, 404, { error: `unknown mock namespace ${selected.namespace}` })
                return
              }
              const job: MockPdfJob = {
                id: randomUUID(),
                event: { status: 'running', phase: 'Queued', percent: 0 },
                subscribers: new Set(),
              }
              pdfJobs.set(job.id, job)
              sendJSON(res, 202, { id: job.id })

              const pdfUrl = pdfUrlForJob(body, selected.namespace)
              void renderDevPdf({
                topology: selected.topology.data, url: pdfUrl, frontpanelDir, pdfAssetsDir,
                onProgress: (progress: DevPdfProgress) => updatePdfJob(job, { status: 'running', ...progress }),
              })
                .then(({ bytes, filename }) => {
                  job.bytes = bytes
                  job.filename = filename
                  updatePdfJob(job, { status: 'ready', phase: 'PDF ready', percent: 100 })
                })
                .catch((error: unknown) => {
                  const message = error instanceof Error ? error.message : 'PDF export failed'
                  updatePdfJob(job, { status: 'error', phase: 'PDF export failed', message })
                })
            })
            .catch(() => sendJSON(res, 400, { error: 'invalid PDF job request' }))
          return
        }
        next()
        return
      }
      const url = new URL(req.url ?? '/', 'http://localhost')
      const pdfJobMatch = /^\/api\/pdf\/jobs\/([^/]+)\/(status|events|download)$/.exec(url.pathname)
      if (pdfJobMatch) {
        cleanupPdfJobs()
        const job = pdfJobs.get(pdfJobMatch[1])
        if (!job) {
          sendJSON(res, 404, { error: 'PDF job not found' })
          return
        }
        if (pdfJobMatch[2] === 'status') {
          sendJSON(res, 200, job.event)
          return
        }
        if (pdfJobMatch[2] === 'events') {
          sendPdfJobSSE(req, res, job)
          return
        }
        if (job.event.status === 'ready' && job.bytes && job.filename) {
          sendPDF(res, job.bytes, job.filename)
          return
        }
        if (job.event.status === 'error') {
          sendJSON(res, 500, { error: job.event.message || 'PDF export failed' })
          return
        }
        sendJSON(res, 409, { error: 'PDF job is still running' })
        return
      }
      if (url.pathname === '/api/namespaces') {
        sendJSON(res, 200, mockNamespaces)
        return
      }
      if (url.pathname === '/api/namespaces/stream') {
        sendSSE(req, res, JSON.stringify(mockNamespaces))
        return
      }
      if (url.pathname === '/api/topology') {
        const selected = selectedTopology(url)
        if (!selected.topology) {
          sendJSON(res, 404, { error: `unknown mock namespace ${selected.namespace}` })
          return
        }
        res.statusCode = 200
        res.setHeader('Content-Type', 'application/json')
        res.end(selected.topology.json)
        return
      }
      if (url.pathname === '/api/topology/stream') {
        const selected = selectedTopology(url)
        if (!selected.topology) {
          sendJSON(res, 404, { error: `unknown mock namespace ${selected.namespace}` })
          return
        }
        if (selected.topology.json.length > 1_000_000) sendHeartbeatSSE(req, res)
        else sendSSE(req, res, selected.topology.json)
        return
      }
      if (url.pathname === '/pdf') {
        const selected = selectedTopology(url)
        if (!selected.topology) {
          sendJSON(res, 404, { error: `unknown mock namespace ${selected.namespace}` })
          return
        }
        void renderDevPdf({ topology: selected.topology.data, url, frontpanelDir, pdfAssetsDir })
          .then(({ bytes, filename }) => sendPDF(res, bytes, filename))
          .catch((error: unknown) => {
            const status = error instanceof DevPdfRequestError ? error.status : 500
            const message = error instanceof Error ? error.message : 'PDF export failed'
            sendJSON(res, status, { error: message })
          })
        return
      }
      next()
    })
  },
})

// Front-panel SVGs live with the operator (which serves them in prod from STENCIL_DIR), so in dev
// they're outside vite's public/. This plugin serves /frontpanel/<name>.svg from that dir and, since
// they're not in the module graph, pings the client on edits (the viewer re-fetches the panel).
const pdfAssetsDir = fileURLToPath(new URL('../operators/cable-map/internal/server/pdfassets', import.meta.url))
const frontpanelDir = fileURLToPath(new URL('../operators/cable-map/frontpanel', import.meta.url))
const isPanel = (f: string) => f.replace(/\\/g, '/').includes('/operators/cable-map/frontpanel/') && f.endsWith('.svg')
const frontpanel = (): Plugin => ({
  name: 'cable-map-frontpanel',
  configureServer(server: ViteDevServer) {
    server.middlewares.use((req: IncomingMessage, res: ServerResponse, next: (err?: unknown) => void) => {
      const url = new URL(req.url ?? '/', 'http://localhost')
      if (!url.pathname.startsWith('/frontpanel/') || !url.pathname.endsWith('.svg')) {
        next()
        return
      }
      const name = decodeURIComponent(url.pathname.slice('/frontpanel/'.length))
      if (!name || name.includes('/') || name.includes('\\') || name.includes('..')) {
        next()
        return
      }
      fs.readFile(path.join(frontpanelDir, name), (err, buf) => {
        if (err) { res.statusCode = 404; res.end(); return }
        res.setHeader('Content-Type', 'image/svg+xml')
        res.end(buf)
      })
    })
    server.watcher.add(frontpanelDir)
    const notify = (file: string) => { if (isPanel(file)) server.ws.send({ type: 'custom', event: 'cable-map:frontpanel' }) }
    server.watcher.on('add', notify)
    server.watcher.on('change', notify)
    server.watcher.on('unlink', notify)
  },
})

// https://vite.dev/config/
export default defineConfig({
  // relative base so assets/fetches resolve under any mount point — works at / and
  // behind EDA's HttpProxy sub-path (/core/httpproxy/v1/cable-map/).
  base: './',
  // force a single React instance — the dep optimizer can otherwise pre-bundle a second copy for
  // MUI/emotion, producing "Invalid hook call / more than one copy of React" at runtime.
  resolve: { dedupe: ['react', 'react-dom', '@emotion/react', '@emotion/styled'] },
  plugins: [react(), frontpanel(), ...(!apiTarget ? [mockApiPlugin()] : [])],
  server: {
    host: '0.0.0.0',
    port: 5173,
    proxy: apiTarget ? {
      '/api': { target: apiTarget, changeOrigin: true },
      '/pdf': { target: apiTarget, changeOrigin: true },
    } : undefined,
  },
})
